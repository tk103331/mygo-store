//go:embed data/apps.json
var catalogJSON []byte

// App is one entry of the Awesome MyGo showcase.
type App struct {
	Slug        string   `json:"slug"`
	Name        string   `json:"name"`
	Author      string   `json:"author"`
	Kind        string   `json:"kind"`      // native or web
	Platforms   []string `json:"platforms"` // win, linux, mac
	Group       string   `json:"group"`     // agents, dev, ai, ...
	Category    string   `json:"category"`
	URL         string   `json:"url"`
	Repo        string   `json:"repo"`
	Summary     string   `json:"summary"`
	Description string   `json:"description"`
	Added       string   `json:"added"`
	Score       float64  `json:"score"`
	Likes       int      `json:"likes"`
	Stars       *int     `json:"stars"`
	License     string   `json:"license"`
	Icon        string   `json:"icon"`
	Shot        string   `json:"shot"`
}

// Catalog is the snapshot data/apps.json, generated by scripts/sync.py.
type Catalog struct {
	Source string `json:"source"`
	AsOf   string `json:"asOf"`
	Apps   []App  `json:"apps"`
}

func loadCatalog() *Catalog {
	var catalog Catalog
	if err := json.Unmarshal(catalogJSON, &catalog); err != nil {
		panic(fmt.Sprintf("mygo-store: data/apps.json: %v", err))
	}
	if len(catalog.Apps) == 0 {
		panic("mygo-store: data/apps.json has no apps")
	}
	return &catalog
}

