// groupLabel and groupBlurb say a group's name and description in the
// language of locale, "" for the source language.
func groupLabel(locale, id string) string {
	return locales.Catalog.Format(locale, "group_"+id+"_label", nil)
}

func groupBlurb(locale, id string) string {
	return locales.Catalog.Format(locale, "group_"+id+"_blurb", nil)
}

func (a *App) kindLabel(msgs locales.Messages) string {
	if a.Kind == "web" {
		return msgs.KindWeb()
	}
	return msgs.KindNative()
}

func (a *App) kindShort(msgs locales.Messages) string {
	if a.Kind == "web" {
		return msgs.KindWebShort()
	}
	return msgs.KindNativeShort()
}

func (a *App) platformLabels() []string {
	order := []string{"mac", "win", "linux"}
	names := map[string]string{"mac": "macOS", "win": "Windows", "linux": "Linux"}
	var out []string
	for _, p := range order {
		for _, q := range a.Platforms {
			if p == q {
				out = append(out, names[p])
			}
		}
	}
	return out
}

func (a *App) platformShort() string {
	names := map[string]string{"mac": "macOS", "win": "Windows", "linux": "Linux"}
	var out []string
	for _, p := range []string{"win", "linux", "mac"} {
		for _, q := range a.Platforms {
			if p == q {
				out = append(out, names[p])
			}
		}
	}
	return strings.Join(out, " · ")
}

func (a *App) categoryLabel(locale string) string {
	return groupLabel(locale, a.Group)
}

func (a *App) starsText() string {
	if a.Stars == nil {
		return ""
	}
	return formatCount(*a.Stars)
}

func formatCount(n int) string {
	if n < 1000 {
		return fmt.Sprint(n)
	}
	if n < 10000 {
		return fmt.Sprintf("%.1fk", float64(n)/1000)
	}
	return fmt.Sprintf("%.0fk", float64(n)/1000)
}

func (a *App) addedDate() string {
	if len(a.Added) < 10 {
		return a.Added
	}
	return a.Added[:10]
}

// Sorting is the order of the apps in a group, a search, or Discover.
type SortMode int

const (
	sortRecommended SortMode = iota // score, highest first
	sortNewest                      // added, newest first
	sortHottest                     // likes, then stars
)

func (m SortMode) Label(msgs locales.Messages) string {
	switch m {
	case sortNewest:
		return msgs.SortNewest()
	case sortHottest:
		return msgs.SortHottest()
	default:
		return msgs.SortRecommended()
	}
}

func sortApps(apps []App, mode SortMode) {
	sort.SliceStable(apps, func(i, j int) bool {
		a, b := apps[i], apps[j]
		switch mode {
		case sortNewest:
			if a.Added != b.Added {
				return a.Added > b.Added
			}
		case sortHottest:
			if a.Likes != b.Likes {
				return a.Likes > b.Likes
			}
			as, bs := 0, 0
			if a.Stars != nil {
				as = *a.Stars
			}
			if b.Stars != nil {
				bs = *b.Stars
			}
			if as != bs {
				return as > bs
			}
		}
		if a.Score != b.Score {
			return a.Score > b.Score
		}
		return strings.ToLower(a.Name) < strings.ToLower(b.Name)
	})
}

// matches reports whether query matches the app: its name, author, summary,
// description, group or repository, case-insensitively. The group and kind
// are matched in the language of locale.
func (a *App) matches(query, locale string) bool {
	q := strings.ToLower(strings.TrimSpace(query))
	if q == "" {
		return true
	}
	msgs := locales.In(locale)
	hay := strings.ToLower(strings.Join([]string{
		a.Name, a.Author, a.Slug, a.Summary, a.Description,
		a.categoryLabel(locale), a.kindLabel(msgs), a.Repo, a.platformShort(),
	}, " "))
	return strings.Contains(hay, q)
}

// filterApps returns the apps shown for the current page and filters.
func (s *store) filterApps() []App {
	var out []App
	query := strings.TrimSpace(s.query)
	for _, app := range s.catalog.Apps {
		if query != "" {
			if !app.matches(query, s.locale) {
				continue
			}
		} else {
			switch {
			case s.nav == "discover":
				continue
			case s.nav == "favorites":
				if !s.prefs.Favorites[app.Slug] {
					continue
				}
			case s.nav == "acquired":
				if !s.isAcquired(app.Slug) {
					continue
				}
			case strings.HasPrefix(s.nav, "group:"):
				if app.Group != strings.TrimPrefix(s.nav, "group:") {
					continue
				}
			default:
				continue
			}
		}
		if s.kind == "native" && app.Kind != "native" {
			continue
		}
		if s.kind == "web" && app.Kind != "web" {
			continue
		}
		if s.platform != "" && !hasPlatform(&app, s.platform) {
			continue
		}
		out = append(out, app)
	}
	sortApps(out, s.sort)
	return out
}

func hasPlatform(app *App, platform string) bool {
	for _, p := range app.Platforms {
		if p == platform {
			return true
		}
	}
	return false
}

// groupApps returns the apps of a group, sorted for Discover.
func (s *store) groupApps(group string, limit int) []App {
	var out []App
	for _, app := range s.catalog.Apps {
		if app.Group == group {
			out = append(out, app)
		}
	}
	sortApps(out, s.sort)
	if limit > 0 && len(out) > limit {
		out = out[:limit]
	}
	return out
}

func (s *store) groupCount(group string) int {
	n := 0
	for i := range s.catalog.Apps {
		if s.catalog.Apps[i].Group == group {
			n++
		}
	}
	return n
}

func (s *store) appBySlug(slug string) *App {
	for i := range s.catalog.Apps {
		if s.catalog.Apps[i].Slug == slug {
			return &s.catalog.Apps[i]
		}
	}
	return nil
}

func (s *store) sameAuthor(app *App) []App {
	var out []App
	for _, other := range s.catalog.Apps {
		if other.Author == app.Author && other.Slug != app.Slug {
			out = append(out, other)
		}
	}
	sortApps(out, sortRecommended)
	if len(out) > 3 {
		out = out[:3]
	}
	return out
}

// scoreTier returns the color of a score, as the site's score bar tiers it.
func scoreTier(c *ui.Context, score float64) ui.Color {
	t := c.Theme()
	switch {
	case score >= 80:
		return ui.Oklch(0.72, 0.15, 155) // green
	case score >= 60:
		return ui.Oklch(0.78, 0.14, 85) // amber
	case score >= 40:
		return t.Accent
	default:
		return t.TextMuted
	}
}
